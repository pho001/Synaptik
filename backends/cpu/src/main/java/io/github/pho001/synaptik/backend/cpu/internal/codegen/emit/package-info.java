/**
 * Owns unsupported Java 26 Class-File generation from canonical CPU kernel IR.
 *
 * <p>Emitters consume an already-selected exact scalar or preferred-species typed vector
 * specialization and generate one universal primitive {@code start}/{@code end} loop over its
 * exact ordered typed primitive-array or {@code MemorySegment} carrier pattern. Proved dense
 * heap-array pointwise entries narrow their universal long bounds and bases once, then use
 * integer loop/address locals; other forms retain checked long state. Scalar generation
 * covers the admitted FLOAT64, FLOAT32, INT32, INT64, and BOOL pointwise rows. A separate scalar
 * affine emitter copies represented bits for all six Model data types, including opaque BFLOAT16
 * through {@code short[]} or native-order two-byte {@code MemorySegment} access. Vector generation covers the
 * bounded typed value matrix plus unit-private floating masks and scalar-broadcast BOOL conditions;
 * materialized or general external masks remain scalar. Every unary opcode has a scalar body;
 * FLOOR, CEIL, SIGMOID, GELU tanh approximation, and SiLU remain scalar-compute only. Vector
 * instruction bytecode emission is separate from pure typed vector mathematics. General Tensor
 * power and direct scalar power are also scalar-compute only. FLOAT32 reciprocal square root
 * widens before both {@code StrictMath.sqrt} and the reciprocal and narrows their combined result
 * once. Direct FLOAT32 power widens the represented base and exponent exactly, invokes
 * {@code StrictMath.pow}, and narrows once. Scalar segment access initializes each required
 * native-order typed layout once per generated invocation and reuses its typed local. Dense,
 * scalar-broadcast, last-axis, and block/outer regimes admit
 * unmasked complete vectors followed by the existing scalar body for every remainder. Proved
 * dense arrays compute one integer vector bound, execute one vector loop, and then one scalar
 * tail while retaining the preferred species in one local; the general
 * odometer remains scalar. Emitters consume the already-typed CPU opcode sequence and do not
 * inspect graph nodes, choose numerical policy, select a
 * route, orchestrate workers, bind Runtime resources, or persist artifacts. Generated bytes are
 * verified before definition and are handed to the cache and executable packages as strongly
 * owned immutable artifact state.
 * The general affine body reads one cold-composed source/result address pair per iteration.
 * Proved dense heap-array affine copies narrow their first pair and bounds once and advance direct
 * integer indexes. Both forms perform no numerical conversion, Shape/layout interpretation,
 * allocation, or vector access.
 * A separate movement emitter consumes compact cold geometry for one static PAD, TILE, CONCAT,
 * STACK, window-extraction, or functional SLICE_UPDATE occurrence and emits a direct
 * represented-bit scalar loop. Proved dense heap-array movement bodies hoist their primitive
 * geometry into integer locals and retain the universal long entry bounds. PAD, CONCAT,
 * UNFOLD_AXIS, UNFOLD2D, and canonical-BOOL axis-zero STACK additionally admit a cold-proved
 * bounded primitive geometry/cursor body independently of heap, segment, or mixed carrier choice;
 * geometry or cursor transitions
 * that cannot be bounded retain the typed general-long body. Slice update walks the output once,
 * selecting update values at
 * signed-sequence positions and base values elsewhere. It uses coordinate and sequence-cursor
 * carry/reset state for arbitrary ranges, performs no per-element division or modulo, and
 * preserves repeated input occurrences without duplicating boundary carriers.
 * The indexing emitter receives compact range-start geometry only after a separate bound scalar
 * pass has validated every logical INT32/INT64 index. It embeds carrier-, type-, and family-
 * specialized GATHER, GATHER_ELEMENTS, GATHER_ND, or canonical-BOOL ONE_HOT writers. Proved dense
 * heap arrays use integer loop/address state; segment, mixed-carrier, and general-layout forms use
 * typed long-address traversal. The writers perform no bounds branch, allocation, or generic
 * {@code Object} bridge and own neither validation nor worker submission.
 * The functional-scatter emitter receives the same direct carriers only after complete bounds
 * validation and, for replacement forms, complete target-uniqueness validation. For
 * SCATTER_ELEMENTS, Gather-compatible SCATTER_ADD, or SCATTER_ND without floating multiplication,
 * each range first copies its disjoint base-output interval and then traverses all logical updates
 * once in row-major order, filtering targets to that interval. Proved dense rank-one heap-array
 * forms narrow bounds and
 * bases once and retain integer loop and address state; segment, mixed-carrier, arbitrary-layout,
 * and otherwise unproved forms retain typed long-address traversal. Family, represented type,
 * reduction, carrier, and access choices are embedded in the generated class rather than selected
 * through a generic execution bridge. Floating multiplication alone receives one assigned scratch
 * slice and retains output-owned grouping so the type-specialized exact-product state machine can
 * consume one complete target group and round the abstract unchanged-format product once; other
 * reductions receive no scratch parameter. The emitter
 * neither validates indices, mutates inputs, nor submits workers.
 * The fold emitter owns a separate output-domain scalar body. It initializes each owned output
 * from represented positive zero, scans logical input occurrences in canonical row-major order,
 * excludes out-of-domain FOLD2D positions geometrically, performs represented sequential
 * addition, and writes each output coordinate once without scratch or atomics. Family, type,
 * carrier, access, coordinate mapping, and addition choices are embedded in the generated class;
 * proved dense heap arrays retain integer coordinate/address state, while segment, mixed-carrier,
 * and general-layout forms normally retain typed long state. One guarded frozen mixed-carrier
 * FLOAT32 FOLD2D geometry instead uses a direct output-cell, kernel-position, then column loop
 * after complete cold proof. It preserves {@code +0.0f} initialization, canonical occurrence
 * order, sequential additions, one output store, arbitrary legal subranges, and the typed
 * general-long fallback. No generic {@code Object} execution bridge is present in generated fold
 * work.
 * The ordering emitter owns a separate logical-slice scalar body. It performs a stable bottom-up
 * merge over two assigned INT64 index regions, compares floating values with NaNs last and
 * directional signed zero, preserves selected represented bits, writes logical-axis INT64
 * indices, and emits both TOP_K outputs from one entry. Family, represented type, direction,
 * output order, carrier, and dense-integer versus general-long address choices are embedded in
 * the generated class; no generic ordering execution bridge remains. Parallel orchestration
 * supplies disjoint complete slices and scratch regions; vector sorting and worker submission
 * remain outside it.
 *
 * <p>The random emitter embeds typed initializer and dropout state, mapping, threshold, value,
 * mask, and loop work without a generic execution bridge. A dedicated {@code [0,0)} prologue
 * writes state exactly once before scalar or parallel element ranges; each dropout element
 * derives its word from the global logical ordinal and writes one canonical BOOL byte plus its
 * exact FLOAT64/FLOAT32 result. Dense arrays use integer address state, while arbitrary layouts
 * and segment or mixed carriers normally use typed long addressing. One guarded frozen rank-one
 * {@code 1 << 20} FLOAT32 mixed-carrier form uses primitive integer cursors while preserving the
 * exact V1 state/mapping/threshold/mask/value order, its {@code [0,0)} state prologue, arbitrary
 * legal subranges, and the typed general-long fallback.</p>
 *
 * <p>The scan emitter embeds a typed two-boundary body over complete independent slice ordinals.
 * It reconstructs non-axis coordinates once per slice, walks the selected axis sequentially in
 * the requested direction, applies inclusive or exclusive placement, and retains same-type
 * FLOAT64/FLOAT32 or modular INT32/INT64 accumulators. BFLOAT16 widens to FLOAT32 and rounds back
 * after every visited value. Dense rank-one heap arrays use a direct integer-address loop;
 * arbitrary layouts and segment carriers retain typed long-address traversal. Parallel
 * orchestration never splits a slice.</p>
 *
 * <p>The aggregate emitter embeds typed scalar bodies for numerical, extrema, and Boolean rows.
 * It owns complete output cells, walks selected coordinates in canonical logical row-major order,
 * emits direct exact floating sum/product limb state and one final rounding, preserves extrema
 * first-NaN bits and signed-zero selection, emits canonical Boolean results, and allocates no
 * object per output cell or selected element. Proved dense heap-array reductions use direct
 * integer-address loops. A cold-proved rank-two canonical-BOOL ANY form with one zero-stride
 * selected axis uses a direct primitive fold that preserves every logical visit; other current
 * forms retain typed general long-address bodies.</p>
 *
 * <p>Covered scalar activation formulas, BFLOAT16 scan arithmetic and rounding, and aggregate
 * extrema/Boolean combination are emitted directly. Those per-element bodies therefore have no
 * runtime reference to another Synaptik class. The selected bounded movement classes likewise
 * contain their primitive geometry, cursor, carrier access, and represented-bit store work
 * directly. The separate {@code CpuVectorMath} call remains
 * limited to one call per emitted vector instruction per vector chunk; scalar tails use the same
 * direct scalar formulas as scalar-only artifacts.</p>
 *
 * <p>Generation and verification are cold-path operations. Only the resolved static entry handle
 * executes on the Runtime hot path. Parallel plans reuse that direct scalar or vector entry for
 * already-bound disjoint chunks; generated code contains no parallel scheduler or strategy switch.
 */
