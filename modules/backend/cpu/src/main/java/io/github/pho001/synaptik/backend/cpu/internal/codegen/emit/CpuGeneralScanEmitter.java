        /**
         * Reuses exact producer/terminal handles through already proved views and broadcasts.
         * An immutable scalar hoist binds directly to its dominating typed handle; no row-local
         * operand copy is emitted. Its existing nonempty-active-domain gate remains the owner.
         * @param region complete origin and coefficient facts
         * @param values shared producing feature/terminal handles
         * @param v operand ordinal
         * @param enclosing right-aligned consuming coordinates
         * @return exact typed handle, or minus one for an existing storage operand
         */
        private int regionalValueLocal(io.github.pho001.synaptik.backend.cpu.internal.ir.CpuRowMapReductionIr region,
                int[][] values,int v,int[] enclosing) {
            int root = region.viewOrigins().get(v);
            if (hoisted.contains(root)) return locals[root];
            if (values[root].length == 0 || values[root][0] < 0) return -1;
            var access = region.accesses().get(v); long offset = 0; int shift = enclosing.length-access.plan().iterationRank();
            var origin = region.accesses().get(root);
            long unitC = region.rowAxes().get(root) == 1 ? origin.strideConstants().get(0) : 1;
            long unitF = region.rowAxes().get(root) == 1 ? origin.strideBatchFactors().get(0) : 0;
            for (int a = 0; a < access.plan().iterationRank(); a++) if (a != region.rowAxes().get(v)) {
                int c = access.extentConstants().get(a) == 1 && access.extentBatchFactors().get(a) == 0 ? 0 : enclosing[shift+a];
                long stride = unitC != 0 ? access.strideConstants().get(a)/unitC
                        : unitF != 0 ? access.strideBatchFactors().get(a)/unitF : 0;
                offset += c*stride;
            }
            return values[root][Math.toIntExact(offset)];
        }

