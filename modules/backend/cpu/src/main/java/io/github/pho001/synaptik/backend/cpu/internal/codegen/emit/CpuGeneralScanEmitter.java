        /**
         * Computes a helper's selected view byte address without a temporal lookup in its loop.
         * @param v exact view ordinal
         * @param logical right-aligned logical coordinates, minus one for R
         * @param row INT current row
         * @param write whether to use the dense producing destination instead of read strides
         */
        private void helperAddress(int v,int[] logical,int row,boolean write) {
            var region = plan.rowMapReductionIr().orElseThrow(); var a = region.accesses().get(v);
            int rank = a.plan().iterationRank(), root = region.viewOrigins().get(v);
            code.lload(write ? helperTargetBases[v] : bases[root]);
            for (int axis = 0; axis < rank; axis++) {
                int coordinate = logical[logical.length-rank+axis];
                if (!write && a.extentConstants().get(axis) == 1 && a.extentBatchFactors().get(axis) == 0) continue;
                if (coordinate == 0) continue;
                Long fixedStride = write ? null : longConstants.get(helperStrides[v][axis]);
                if (fixedStride != null && fixedStride == 0) continue;
                if (coordinate > 0 && fixedStride != null) { code.loadConstant(coordinate*fixedStride).ladd(); continue; }
                if (coordinate < 0) code.iload(row).i2l(); else code.loadConstant((long)coordinate);
                if (write) {
                    long stride = width;
                    for (int j = axis+1; j < rank; j++) stride *= a.extentConstants().get(j);
                    if (stride != 1) code.loadConstant(stride).lmul();
                } else if (fixedStride == null || fixedStride != 1) { loadByteFact(helperStrides[v][axis]); code.lmul(); }
                code.ladd();
            }
            code.lstore(address);
        }

        /**
         * Updates selected physical bindings, joins prebound ranges, then merges before the
         * distinct shared carry ADD sites. The caller performs no concurrent arithmetic.
         * @param stage selected region and its existing per-time shared epilogue
         */
