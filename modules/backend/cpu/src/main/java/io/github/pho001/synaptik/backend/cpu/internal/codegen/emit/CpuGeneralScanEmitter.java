        /**
         * Keeps the vector finish narrowly within represented terminal carry ADD sites.
         * @param stage selected region and existing finish sites
         * @return whether all finish sites have the proved same-feature ADD binding
         */
        private boolean vectorEpilogue(CpuGeneralScanIr.Stage stage) {
            var region = plan.rowMapReductionIr().orElseThrow();
            return stage.epilogue().stream().allMatch(v -> {
                var instruction = instructions.get(v);
                if (instruction.opcode() != io.github.pho001.synaptik.backend.cpu.internal.ir.CpuPointwiseOpcode.ADD) return false;
                for (int p = 0; p < 2; p++) {
                    int terminal = region.viewOrigins().get(instruction.inputs().get(p));
                    int formal = ir.formalOrdinals().indexOf(region.viewOrigins().get(instruction.inputs().get(1-p)));
                    if (region.terminalOutputs().contains(terminal) && formal >= 0 && formal < ir.carryCount()
                            && ir.nextOrdinals().get(formal) == v
                            && region.accesses().get(v).extentConstants().equals(region.accesses().get(terminal).extentConstants())
                            && region.accesses().get(v).extentBatchFactors().equals(region.accesses().get(terminal).extentBatchFactors())) return true;
                }
                return false;
            });
        }

        /**
         * Merges completed private feature vectors in fixed range order, then executes the
         * proved distinct per-time carry ADDs. Invalid slots dominate all partial reads and the
         * first valid slot moves raw, preserving geometry-singleton represented SUM.
         * @param stage selected region with proved same-shape terminal/carry ADD finish
         */
        private void mergeVectorRegion(CpuGeneralScanIr.Stage stage) {
            var region = plan.rowMapReductionIr().orElseThrow(); int count = plan.views().size();
            int lanes = specialization.vectorSpeciesBitSize()/type.bitWidth();
            int[][] values = new int[count][]; long cells = 0;
            for (int v = 0; v < count; v++) values[v] = new int[0];
            for (int out : region.terminalOutputs()) {
                int n = region.accesses().get(out).plan().iterationRank() == 0 ? 1 : Math.toIntExact(region.accesses().get(out).extentConstants().getLast());
                int size = regionalCells(region,out,false); cells += size;
                values[out] = new int[n == 0 ? 0 : size/n*((n+lanes-1)/lanes)];
                for (int b = 0; b < values[out].length; b++) { values[out][b] = code.allocateLocal(TypeKind.REFERENCE); CpuAggregateEmitter.emitRepresentedVectorInit(code,type,values[out][b],false); }
            }
            long slice = 8+((cells*width+7)&~7L), stageBytes = stagingBytes();
            int range = code.allocateLocal(TypeKind.INT), seen = code.allocateLocal(TypeKind.INT), partial = code.allocateLocal(TypeKind.LONG);
            code.loadConstant(0).istore(range).loadConstant(0).istore(seen);
            var loop = code.newLabel(); var next = code.newLabel(); var done = code.newLabel(); var add = code.newLabel(); var merged = code.newLabel();
            code.labelBinding(loop).iload(range).iload(rowRangeCount).branch(Opcode.IF_ICMPGE,done);
            code.lload(rowPrivateBase).loadConstant(stageBytes).ladd().iload(range).i2l().loadConstant(slice).lmul().ladd().lstore(partial);
            carrier.loadBytes(DataType.INT64,scratch,partial); code.loadConstant(0L).lcmp().branch(Opcode.IFEQ,next);
            code.iload(seen).branch(Opcode.IFNE,add);
            for (boolean accumulate : List.of(false,true)) {
                if (accumulate) code.labelBinding(add);
                long offset = 8;
                for (int out : region.terminalOutputs()) {
                    int n = region.accesses().get(out).plan().iterationRank() == 0 ? 1 : Math.toIntExact(region.accesses().get(out).extentConstants().getLast());
                    for (int block = 0; block < values[out].length; block++) {
                        int[] logical = vectorCoordinates(region,out,block,false,lanes);
                        int column = logical.length == 0 ? 0 : logical[logical.length-1];
                        int cell = block/((n+lanes-1)/lanes)*n+column, mask = rowMasks.get(Math.min(lanes,n-column));
                        long byteOffset = offset+cell*width;
                        CpuAggregateEmitter.emitRepresentedVectorContributorStep(code,type,values[out][block],!accumulate,() -> {
                            code.lload(partial).loadConstant(byteOffset).ladd().lstore(address);
                            carrier.vectorLoadBytes(type,scratch,address,mask);
                        });
                    }
                    offset += regionalCells(region,out,false)*width;
                }
                if (!accumulate) code.branch(Opcode.GOTO,merged);
            }
            code.labelBinding(merged).loadConstant(1).istore(seen).labelBinding(next).iinc(range,1).branch(Opcode.GOTO,loop).labelBinding(done);
            for (int out : region.terminalOutputs()) for (int block = 0; block < values[out].length; block++)
                regionalVectorStore(out,vectorCoordinates(region,out,block,false,lanes),-1,values[out][block],lanes,rowMasks);
            var vector = ClassDesc.of("jdk.incubator.vector."+(type == DataType.FLOAT64 ? "DoubleVector" : "FloatVector"));
            var species = ClassDesc.of("jdk.incubator.vector.VectorSpecies");
            finishVectorRegion(stage,values,(v,logical) -> {
                int root = region.viewOrigins().get(v);
                var a = region.accesses().get(v); int rank = a.plan().iterationRank();
                int n = rank == 0 ? 1 : Math.toIntExact(a.extentConstants().getLast());
                int column = logical.length == 0 ? 0 : logical[logical.length-1];
                if (region.terminalOutputs().contains(root)) {
                    int offset = featureOffset(region,v,logical);
                    code.aload(values[root][offset/n*((n+lanes-1)/lanes)+(offset%n)/lanes]); return;
                }
                int formal = ir.formalOrdinals().indexOf(root);
                boolean scalarRead = ir.scalarReads().get(ir.actualReads().get(formal));
                boolean changing = plan.carryOffsets().get(formal) >= 0 || plan.carryPorts().get(formal) >= 0;
                if (rank == 0 || scalarRead && !changing) {
                    code.getstatic(vector,"SPECIES_PREFERRED",species); regionalAddress(v,logical,-1,false);
                    carrier.loadBytes(type,carriers[root],address);
                    code.invokestatic(vector,"broadcast",MethodTypeDesc.of(vector,species,kind.upperBound())); return;
                }
                var dense = code.newLabel(); var loaded = code.newLabel();
                if (scalarRead) {
                    if (ir.symbolic()) loadByteFact(batchStrides[v][rank-1]); else code.lload(factors[root]);
                    code.loadConstant(0L).lcmp().branch(Opcode.IFNE,dense);
                    code.getstatic(vector,"SPECIES_PREFERRED",species); regionalAddress(v,logical,-1,false);
                    carrier.loadBytes(type,carriers[root],address);
                    code.invokestatic(vector,"broadcast",MethodTypeDesc.of(vector,species,kind.upperBound()));
                    code.branch(Opcode.GOTO,loaded).labelBinding(dense);
                }
                regionalAddress(v,logical,-1,false); carrier.vectorLoadBytes(type,carriers[root],address,rowMasks.get(Math.min(lanes,n-column)));
                if (scalarRead) code.labelBinding(loaded);
            },lanes,rowMasks);
        }

