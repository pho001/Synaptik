    public boolean lengthAware() { return composition.map(Composition::lengthAware).orElseGet(() -> stages.map(s -> s.rowCarryCount() > 0).orElse(false)); }

    /**
     * Identifies discrete control independently of floating formals and deduplicated reads.
     * @return the unique length-control boundary, or minus one in legacy modes
     */
    public int lengthRead() { return composition.map(Composition::lengthRead).orElseGet(() -> stages.map(Stages::lengthRead).orElse(-1)); }

    /**
     * Separates discrete control storage from homogeneous body arithmetic.
     * @param position ordered unique-read or demanded-write boundary
     * @return INT64 only at the explicit control position, otherwise the body dtype
     */
    public DataType boundaryType(int position) {
        return composition.map(c -> c.boundaryTypes().get(position))
                .orElseGet(() -> position == lengthRead() ? DataType.INT64 : dataType());
    }

