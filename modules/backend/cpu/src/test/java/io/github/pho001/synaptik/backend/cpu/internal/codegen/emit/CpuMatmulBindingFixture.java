/** Actual joint compiled forward/AD consumer against independent, preallocated Java mathematics. */
final class CpuMatmulBindingFixture implements AutoCloseable {
    final Arena arena = Arena.ofConfined();
    final DataType type;
    private final boolean length;
    final Runnable production, direct;
    final long compileNanos, prepareBindNanos;
    private final Consumer consumer;
    private final List<MemorySegment> actual = new ArrayList<>(), expected = new ArrayList<>();

    /**
     * Compiles and prepares T4/B7/F3/H2 with public final/emission seed inputs, then checks every
     * published forward result and requested gradient. Fresh AD uses its actual activity plan and
     * production orchestration, not reconstructed phase arguments or historical generated bytes.
     * @param type FLOAT32 or FLOAT64 represented type
     * @param length whether to use TANH recurrence and lengths [4,0,1,3,2,4,1]
     * @throws Throwable if compilation, preparation, binding or numerical checks fail
     */
    CpuMatmulBindingFixture(DataType type, boolean length) throws Throwable {
        this.type = type; this.length = length;
        Consumer prepared = null;
        try {
            long started = System.nanoTime();
            Tensor h = tensor(type,true,7,2), x = tensor(type,true,7,3);
            Tensor w = tensor(type,true,3,2), u = tensor(type,true,2,2), bias = tensor(type,true,2);
            Tensor next = length ? x.matmul(w).add(h.matmul(u)).add(bias).tanh() : h.add(x.matmul(w));
            Tensor initial = tensor(type,true,7,2), sequence = tensor(type,true,4,7,3);
            Tensor weight = tensor(type,true,3,2), recurrent = tensor(type,true,2,2), offset = tensor(type,true,2);
            Tensor lengths = tensor(DataType.INT64,false,7);
            var formals = length ? List.of(w,u,bias) : List.of(w);
            var parameters = length ? List.of(weight,recurrent,offset) : List.of(weight);
            var body = new ScanBody(List.of(h),List.of(x),formals,List.of(next),List.of(next));
            var scan = length ? Scan.apply(List.of(initial),List.of(sequence),parameters,lengths,1,
                    List.of(OptionalInt.of(0)),body,false)
                    : Scan.apply(List.of(initial),List.of(sequence),parameters,body,false);
            var roots = List.of(scan.finalCarry().getFirst(),scan.outputs().getFirst());
            var targets = new ArrayList<>(List.of(initial,sequence)); targets.addAll(parameters);
            Tensor finalSeed = tensor(type,false,7,2), emissionSeed = tensor(type,false,4,7,2);
            var request = new FunctionalGradientRequest(List.of(new FunctionalGradientRequest.Stage(
                    roots.stream().map(t -> (FunctionalGradientRequest.OutputReference)
                            new FunctionalGradientRequest.ForwardTensorReference(t)).toList(),
                    List.of(Optional.of(finalSeed),Optional.of(emissionSeed)),targets,false,
                    FunctionalGradientRequest.DisconnectedPolicy.ZERO)));
            var compiled = CpuGeneralScanCapabilityTest.compile(roots,Optional.of(request),false,new CpuCapabilityProvider());
            compileNanos = System.nanoTime()-started;
            started = System.nanoTime();
            prepared = new Consumer(compiled,OptionalLong.empty());
            consumer = prepared;
            consumer.numbers(initial,values(14,.007)); consumer.numbers(sequence,values(84,.014));
            consumer.numbers(weight,values(6,.021));
            if (length) {
                consumer.numbers(recurrent,values(4,.028)); consumer.numbers(offset,values(2,.035));
            }
            consumer.numbers(finalSeed,values(14,.042)); consumer.numbers(emissionSeed,values(56,.049));
            if (length) {
                long[] counts = {4,0,1,3,2,4,1}; consumer.raw(lengths,counts);
                var inputs = consumer.inputStorage(sequence); var seeds = consumer.inputStorage(emissionSeed);
                for (int row = 0; row < 7; row++) for (int t = (int)counts[row]; t < 4; t++) {
                    for (int feature = 0; feature < 3; feature++) put(inputs,(t*7L+row)*3+feature,Double.NaN);
                    for (int col = 0; col < 2; col++) put(seeds,(t*7L+row)*2+col,Double.NaN);
                }
            }
            consumer.bind();
            production = consumer::execute;
            prepareBindNanos = System.nanoTime()-started;
            for (int p = 0; p < compiled.publication().forwardBindings().size(); p++) actual.add(consumer.forwardStorage(p));
            for (int p = 0; p < compiled.publication().gradientBindings().size(); p++) actual.add(consumer.gradientStorage(p));
            for (var segment : actual) expected.add(arena.allocate(segment.byteSize(),type.byteWidth()));
            var initialStorage = consumer.inputStorage(initial); var xs = consumer.inputStorage(sequence);
            var ws = consumer.inputStorage(weight); var fs = consumer.inputStorage(finalSeed);
            var es = consumer.inputStorage(emissionSeed);
            var result = expected.get(0); var emissions = expected.get(1); var dh = expected.get(2);
            var dx = expected.get(3); var dw = expected.get(4);
            var forwardWork = arena.allocate(42L*type.byteWidth(),type.byteWidth());
            var reverseWork = arena.allocate(40L*type.byteWidth(),type.byteWidth());
            if (length) {
                var us = consumer.inputStorage(recurrent); var bs = consumer.inputStorage(offset);
                var ls = consumer.inputStorage(lengths);
                var previous = arena.allocate(56L*type.byteWidth(),type.byteWidth());
                var saved = arena.allocate(56L*type.byteWidth(),type.byteWidth());
                var du = expected.get(5); var db = expected.get(6);
                direct = type == DataType.FLOAT64 ? () -> {
                    CpuMatmulBindingCleanJavaOracle.forwardFloat64(initialStorage,xs,ws,us,bs,ls,result,emissions,previous,saved,forwardWork);
                    CpuMatmulBindingCleanJavaOracle.reverseFloat64(xs,ws,us,ls,fs,es,previous,saved,dh,dx,dw,du,db,reverseWork);
                } : () -> {
                    CpuMatmulBindingCleanJavaOracle.forwardFloat32(initialStorage,xs,ws,us,bs,ls,result,emissions,previous,saved,forwardWork);
                    CpuMatmulBindingCleanJavaOracle.reverseFloat32(xs,ws,us,ls,fs,es,previous,saved,dh,dx,dw,du,db,reverseWork);
                };
            } else {
                var zero = arena.allocate(type.byteWidth(),type.byteWidth());
                direct = type == DataType.FLOAT64 ? () -> {
                    CpuGeneralScanCleanJavaOracle.matmulForwardFloat64(initialStorage,xs,ws,result,emissions,4,7,3,2);
                    CpuGeneralScanCleanJavaOracle.matmulReverseFloat64(fs,es,xs,ws,zero,dh,dw,dx,reverseWork,4,7,3,2);
                } : () -> {
                    CpuGeneralScanCleanJavaOracle.matmulForward(initialStorage,xs,ws,result,emissions,4,7,3,2);
                    CpuGeneralScanCleanJavaOracle.matmulReverse(fs,es,xs,ws,zero,dh,dw,dx,reverseWork,4,7,3,2);
                };
            }
            verify();
        } catch (Throwable failure) {
            if (prepared != null) prepared.close();
            arena.close();
            throw failure;
        }
    }

    /** Executes the actual joint production invocation and independent joint Java control. */
    void verify() { production.run(); direct.run(); verifyLatest(); }

    /** Checks every published forward/gradient cell without executing another arm. */
    void verifyLatest() {
        for (int p = 0; p < actual.size(); p++)
            for (long i = 0; i < actual.get(p).byteSize()/type.byteWidth(); i++) {
                double reference = get(expected.get(p),i), observed = get(actual.get(p),i);
                assertEquals(reference,observed,type == DataType.FLOAT64 ? 2e-14 : 2e-6,"port="+p+" cell="+i);
            }
        if (length) {
            long[] counts = {4,0,1,3,2,4,1};
            for (int row = 0; row < 7; row++) for (int t = (int)counts[row]; t < 4; t++) {
                for (int col = 0; col < 2; col++) assertEquals(0L,
                        Double.doubleToRawLongBits(get(actual.get(1),(t*7L+row)*2+col)), "inactive emission +0");
                for (int feature = 0; feature < 3; feature++) assertEquals(0L,
                        Double.doubleToRawLongBits(get(actual.get(3),(t*7L+row)*3+feature)), "inactive sequence gradient +0");
            }
        }
    }

    /**
     * Creates one static caller tensor or local formal.
     * @param type exact represented type
     * @param gradient whether it participates in AD
     * @param shape static logical extents
     * @return fresh tensor with canonical layout
     */
    private static Tensor tensor(DataType type, boolean gradient, long... shape) {
        return CpuGeneralScanLoweringTest.tensor(type,gradient,shape);
    }

    /**
     * Creates deterministic nonuniform caller values outside measured invocations.
     * @param count number of represented elements
     * @param scale input-specific finite scale
     * @return fresh finite values, narrowed by the ordinary consumer writer
     */
    private static double[] values(int count, double scale) {
        double[] result = new double[count];
        for (int i = 0; i < count; i++) result[i] = (i%11-5)*scale;
        return result;
    }

    /**
     * Reads one independent or published floating result outside measured invocations.
     * @param segment live readable floating storage
     * @param index logical contiguous element index
     * @return represented value widened for assertions
     */
    private double get(MemorySegment segment,long index) {
        return type == DataType.FLOAT64 ? segment.getAtIndex(ValueLayout.JAVA_DOUBLE,index) : segment.getAtIndex(ValueLayout.JAVA_FLOAT,index);
    }

    /**
     * Poisons inactive caller storage before ordinary production binding.
     * @param segment live writable floating input
     * @param index logical contiguous element index
     * @param value represented poison, narrowed once for FLOAT32
     */
    private void put(MemorySegment segment,long index,double value) {
        if (type == DataType.FLOAT64) segment.setAtIndex(ValueLayout.JAVA_DOUBLE,index,value);
        else segment.setAtIndex(ValueLayout.JAVA_FLOAT,index,(float)value);
    }

    /** Releases the production consumer and independent oracle storage. */
    @Override public void close() {
        try { consumer.close(); } finally { arena.close(); }
    }
}
