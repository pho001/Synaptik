"#undef ORDINARY_UNARY\n"
"inline void numeric_clamp_body(device const uchar *input, device uchar *output, constant ClampMeta &m, ulong linear) {\n"
"    ulong word = load_word(input, linear, lp_width(m.valueType));\n"
"    ulong lower = lp_extreme(word, ulong(m.lower), m.valueType, true);\n"
"    store_word(output, linear, lp_width(m.valueType), lp_extreme(lower, ulong(m.upper), m.valueType, false));\n"
"}\n"
"#define ORDINARY_CLAMP(NAME, CONTROL, GUARD) \\\n"
"kernel void NAME(device const uchar *input [[buffer(0)]], device uchar *output [[buffer(1)]], constant ClampMeta &m [[buffer(2)]], uint3 gid [[thread_position_in_grid]] CONTROL) { ulong linear = linear_id(gid, m.gridWidth, m.gridHeight); if (linear >= m.elementCount) return; GUARD numeric_clamp_body(input, output, m, linear); }\n"
"ORDINARY_CLAMP(numeric_clamp, , )\n"
"#define ORDINARY_CONTROL , device const ulong *scanControl [[buffer(28)]], constant ScanStepControl &scanStep [[buffer(29)]]\n"
"ORDINARY_CLAMP(numeric_clamp_scan, ORDINARY_CONTROL, if (!scan_control_output(scanControl, scanStep, linear)) return;)\n"
"#undef ORDINARY_CONTROL\n"
"#undef ORDINARY_CLAMP\n"
"inline float ordinary_mse_value(device const uchar *left, device const uchar *right, ulong ordinal, constant DataMeta &m) {\n"
"    ulong lo = logical_storage(ordinal, m.inDims, m.inputStrides, m.inputRank, m.inputOffset);\n"
"    ulong ro = logical_storage(ordinal, m.auxDims, m.auxiliaryStrides, m.auxRank, m.auxiliaryOffset);\n"
"    float delta = synaptik_load_numeric(left, lo, m.sourceType) - synaptik_load_numeric(right, ro, m.roleTypes[1]);\n"
"    return delta * delta;\n"
"}\n"
"inline void ordinary_mse_body(device const uchar *left, device const uchar *right, device uchar *output, constant DataMeta &m, ulong linear) {\n"
"    if (m.attrs[0] == 1ul) { synaptik_store_numeric(output, linear, m.targetType, ordinary_mse_value(left, right, linear, m)); return; }\n"
"    ulong count = m.inputExtents[0]; float sum = 0.0f;\n"
"    for (ulong ordinal = 0ul; ordinal < count; ++ordinal) sum += ordinary_mse_value(left, right, ordinal, m);\n"
"    synaptik_store_numeric(output, linear, m.targetType, m.attrs[0] == 3ul ? sum / float(count) : sum);\n"
"}\n"
"#define ORDINARY_MSE(NAME, CONTROL, GUARD) \\\n"
"kernel void NAME(device const uchar *left [[buffer(0)]], device const uchar *right [[buffer(1)]], device uchar *output [[buffer(2)]], constant DataMeta &m [[buffer(3)]], uint3 gid [[thread_position_in_grid]] CONTROL) { ulong linear = data_linear_id(gid, m); if (linear >= m.elementCount) return; GUARD ordinary_mse_body(left, right, output, m, linear); }\n"
"ORDINARY_MSE(numeric_mse, , )\n"
"#define ORDINARY_CONTROL , device const ulong *scanControl [[buffer(28)]], constant ScanStepControl &scanStep [[buffer(29)]]\n"
"ORDINARY_MSE(numeric_mse_scan, ORDINARY_CONTROL, if (!scan_control_output(scanControl, scanStep, linear)) return;)\n"
"#undef ORDINARY_CONTROL\n"
"#undef ORDINARY_MSE\n"
"inline void numeric_cumulative_body(device const uchar *input, device uchar *output, constant ScanMeta &m, ulong line, bool product) {\n"
"    ulong base = (line / m.inner) * m.axisLength * m.inner + line % m.inner;\n"
"    uint type = m.valueType, width = lp_width(type);\n"
"    bool integral = type == 2u || type == 6u;\n"
"    ulong identity = integral ? (product ? 1ul : 0ul) : lp_bool_word(product, 1u);\n"
"    ulong accumulator = identity; bool hasContributor = false;\n"
"    for (ulong step = 0ul; step < m.axisLength; ++step) {\n"
"        ulong logical = m.reverse != 0u ? m.axisLength - 1ul - step : step;\n"
"        ulong offset = base + logical * m.inner;\n"
"        ulong value = load_word(input, offset, width);\n"
"        if (m.exclusive != 0u) store_word(output, offset, width, integral ? accumulator : lp_convert(accumulator, 1u, type));\n"
"        if (!hasContributor) { accumulator = integral ? value : lp_convert(value, type, 1u); hasContributor = true; }\n"
"        else if (type == 2u) accumulator = product ? ulong(uint(accumulator) * uint(value)) : ulong(uint(accumulator) + uint(value));\n"
"        else if (type == 6u) accumulator = product ? accumulator * value : accumulator + value;\n"
"        else { float left = as_type<float>(uint(accumulator)), right = lp_widen(value, type); accumulator = ulong(as_type<uint>(product ? left * right : left + right)); }\n"
"        if (m.exclusive == 0u) store_word(output, offset, width, integral ? accumulator : lp_convert(accumulator, 1u, type));\n"
"    }\n"
"}\n"
"#define ORDINARY_CUMULATIVE(NAME, PRODUCT) \\\n"
"kernel void NAME(device const uchar *input [[buffer(0)]], device uchar *output [[buffer(1)]], constant ScanMeta &m [[buffer(2)]], uint3 gid [[thread_position_in_grid]]) { ulong line = linear_id(gid, m.gridWidth, m.gridHeight); if (line >= m.lineCount) return; numeric_cumulative_body(input, output, m, line, PRODUCT); } \\\n"
"kernel void NAME##_scan(device const uchar *input [[buffer(0)]], device uchar *output [[buffer(1)]], constant ScanMeta &m [[buffer(2)]], uint3 gid [[thread_position_in_grid]], device const ulong *scanControl [[buffer(28)]], constant ScanStepControl &scanStep [[buffer(29)]]) { \\\n"
"    ulong line = linear_id(gid, m.gridWidth, m.gridHeight); if (line >= m.lineCount) return; \\\n"
"    ulong base = (line / m.inner) * m.axisLength * m.inner + line % m.inner; \\\n"
"    if (!scan_control_operand(scanControl, scanStep, 0u, base)) return; numeric_cumulative_body(input, output, m, line, PRODUCT); \\\n"
"}\n"
"ORDINARY_CUMULATIVE(numeric_scan_sum, false)\n"
"ORDINARY_CUMULATIVE(numeric_scan_prod, true)\n"
"#undef ORDINARY_CUMULATIVE\n";

